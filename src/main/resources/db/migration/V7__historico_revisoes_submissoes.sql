ALTER TABLE submissoes_externas ADD COLUMN versao_revisao BIGINT NOT NULL DEFAULT 0;

CREATE TABLE revisoes_submissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submissao_id BIGINT NOT NULL REFERENCES submissoes_externas(id),
    responsavel_id BIGINT NOT NULL REFERENCES usuarios(id),
    responsavel_nome VARCHAR(150) NOT NULL,
    status_anterior VARCHAR(20) NOT NULL CHECK (status_anterior IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    status_novo VARCHAR(20) NOT NULL CHECK (status_novo IN ('APROVADA', 'REJEITADA')),
    justificativa VARCHAR(1000) NOT NULL,
    revisada_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_revisao_muda_status CHECK (status_anterior <> status_novo)
);
CREATE INDEX ix_revisoes_submissao ON revisoes_submissoes(submissao_id, id DESC);
