CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    matricula_ra VARCHAR(30),
    role VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuarios_role
        CHECK (role IN ('ESTUDANTE', 'ORGANIZADOR', 'ADMINISTRADOR'))
);

CREATE UNIQUE INDEX uk_usuarios_email_lower ON usuarios (LOWER(email));
CREATE UNIQUE INDEX uk_usuarios_matricula_ra ON usuarios (matricula_ra)
    WHERE matricula_ra IS NOT NULL;

CREATE TABLE grupos_regulamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_eixo VARCHAR(20) NOT NULL,
    limite_maximo_horas NUMERIC(7, 2) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_grupos_regulamento_categoria UNIQUE (categoria_eixo),
    CONSTRAINT ck_grupos_regulamento_categoria
        CHECK (categoria_eixo IN ('ENSINO', 'PESQUISA', 'EXTENSAO')),
    CONSTRAINT ck_grupos_regulamento_limite CHECK (limite_maximo_horas > 0)
);

CREATE TABLE oportunidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(180) NOT NULL,
    descricao TEXT NOT NULL,
    carga_horaria NUMERIC(6, 2) NOT NULL,
    vagas INTEGER NOT NULL,
    data_inicio TIMESTAMPTZ NOT NULL,
    data_fim TIMESTAMPTZ NOT NULL,
    grupo_horas_id BIGINT NOT NULL,
    organizador_id BIGINT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_oportunidades_carga_horaria CHECK (carga_horaria > 0),
    CONSTRAINT ck_oportunidades_vagas CHECK (vagas > 0),
    CONSTRAINT ck_oportunidades_periodo CHECK (data_fim >= data_inicio),
    CONSTRAINT fk_oportunidades_grupo_horas
        FOREIGN KEY (grupo_horas_id) REFERENCES grupos_regulamento (id),
    CONSTRAINT fk_oportunidades_organizador
        FOREIGN KEY (organizador_id) REFERENCES usuarios (id)
);
CREATE INDEX ix_oportunidades_grupo_horas ON oportunidades (grupo_horas_id);
CREATE INDEX ix_oportunidades_organizador ON oportunidades (organizador_id);
CREATE INDEX ix_oportunidades_data_inicio ON oportunidades (data_inicio);

CREATE TABLE inscricoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    oportunidade_id BIGINT NOT NULL,
    data_inscricao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_participacao VARCHAR(20) NOT NULL DEFAULT 'INSCRITO',
    CONSTRAINT uk_inscricoes_usuario_oportunidade UNIQUE (usuario_id, oportunidade_id),
    CONSTRAINT ck_inscricoes_status
        CHECK (status_participacao IN ('INSCRITO', 'PRESENTE', 'AUSENTE')),
    CONSTRAINT fk_inscricoes_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_inscricoes_oportunidade
        FOREIGN KEY (oportunidade_id) REFERENCES oportunidades (id)
);
CREATE INDEX ix_inscricoes_oportunidade ON inscricoes (oportunidade_id);

CREATE TABLE registros_atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    oportunidade_id BIGINT NOT NULL,
    horas_computadas NUMERIC(6, 2) NOT NULL,
    status_envio_email VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    data_envio TIMESTAMPTZ,
    url_anexo TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_registros_atividade_usuario_oportunidade
        UNIQUE (usuario_id, oportunidade_id),
    CONSTRAINT ck_registros_atividade_horas CHECK (horas_computadas > 0),
    CONSTRAINT ck_registros_atividade_email
        CHECK (status_envio_email IN ('PENDENTE', 'ENVIADO', 'FALHOU')),
    CONSTRAINT fk_registros_atividade_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_registros_atividade_oportunidade
        FOREIGN KEY (oportunidade_id) REFERENCES oportunidades (id)
);
CREATE INDEX ix_registros_atividade_usuario ON registros_atividade (usuario_id);

CREATE TABLE submissoes_externas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    titulo VARCHAR(180) NOT NULL,
    horas_declaradas NUMERIC(6, 2) NOT NULL,
    status_validacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    url_documento TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_submissoes_externas_horas CHECK (horas_declaradas > 0),
    CONSTRAINT ck_submissoes_externas_status
        CHECK (status_validacao IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    CONSTRAINT fk_submissoes_externas_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX ix_submissoes_externas_usuario ON submissoes_externas (usuario_id);
CREATE INDEX ix_submissoes_externas_status ON submissoes_externas (status_validacao);
